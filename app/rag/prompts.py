"""RAG Prompt 模板。

把"用户问题 + 检索到的参考资料"组装成 LLM 能理解的 prompt。

设计原则（v0.5-2 D ext 修订）：
- 两种场景用不同 prompt：
  1. 召回到相关内容 → 严格基于参考资料（这是 RAG 的核心价值）
  2. 没召回 / 召回错 → 允许通用兜底 + 明确告知用户（v0.5-3 接联网搜索）

v0.1 单一 prompt 过度严格（hashmap 思路拒答），v0.5-2 D ext 拆分场景。

Java 类比：相当于 Spring 里写一个 MessageSource，把模板参数化。
"""

# ========== 场景 1：召回到相关内容（严格 RAG） ==========
# 用于 retriever 返了至少 1 个 chunk（score ≥ min_score）
# 此时必须用参考资料，**不允许 LLM 用通用知识补充**
# 因为这才是 RAG 的价值：基于你自己的知识库回答
RAG_SYSTEM_PROMPT_WITH_CONTEXT = """你是一个严谨的学习助手，基于用户上传的参考资料回答问题。

回答要求：
1. **必须基于参考资料**：只基于参考资料中的内容回答（代码、标题、注释、变量名都是信息源）。
2. **可基于现有内容推理**：比如"两数之和"的 hashmap 解法代码就是思路本身，可以基于代码描述思路。
3. **禁止补充外部知识**：不要引入参考资料之外的任何具体事实、数字、API。即使你"知道"答案，只要参考资料里没写，就不能说。
4. **引用原文**：引用关键代码段或句子，方便用户回溯。
5. **中文回答**：用中文回复。
6. **简洁**：直接给结论，不要"根据参考资料..."这种废话开头。

参考资料：
{context}
"""

# ========== 场景 2：没召回到（兜底模式） ==========
# 用于 retriever 没返 chunk（score 全低于 min_score 或库里空）
# 此时允许 LLM 用通用知识兜底，但必须开头告知用户
# 未来 v0.5-3 接联网搜索时，这里的兜底改为搜索结果
RAG_SYSTEM_PROMPT_NO_CONTEXT = """你是一个学习助手。由于未在知识库中找到相关内容，以下回答基于通用知识。

回答要求：
1. **开头告知用户**：第一句话必须说"未在知识库中找到相关内容，以下是通用回答："。
2. **可使用通用知识**：自由作答。
3. **简洁**：直接给结论，不要"作为AI助手..."这种废话开头。
4. **中文回答**：用中文回复。
"""

# 用户提问模板（两种场景共用）
RAG_USER_TEMPLATE = """问题：{question}

请回答。"""