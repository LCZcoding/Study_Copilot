"""RAG Prompt 模板。

把"用户问题 + 检索到的参考资料"组装成 LLM 能理解的 prompt。

设计原则（来自 CODE_CONTEXT.md"严格不做清单"）：
- v0.1 只用最基础的模板，不做 Few-shot、CoT 等高级技巧
- 让 LLM 严格基于参考资料回答（避免幻觉）
- 引用原文方便用户回溯

Java 类比：相当于 Spring 里写一个 MessageSource，把模板参数化。
"""

# 系统提示：定义 LLM 的角色和行为约束。
# 三条规则：1) 只基于参考资料 2) 没答案时明说 3) 引用关键原文
RAG_SYSTEM_PROMPT = """你是一个严谨的学习助手，基于用户上传的参考资料回答问题。

回答要求：
1. **只基于参考资料**：不要引入参考资料之外的知识，不要编造
2. **引用原文**：回答时引用参考资料中的关键句子，方便用户回溯
3. **没答案明说**：如果参考资料中没有相关信息，明确说"参考资料中没有提到该内容"
4. **中文回答**：用中文回复用户
5. **简洁**：直接给结论，不要说"根据参考资料..."这种废话开头

参考资料：
{context}
"""

# 用户提问模板：把问题包成清晰格式
RAG_USER_TEMPLATE = """问题：{question}

请基于上面的参考资料回答。"""